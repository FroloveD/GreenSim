/* Ёмкости: высота горшка/бака по системе и высота, на которой ёмкость стоит.
   В теплице растения на желобах (0.16 м), в комнате и на балконе — на полу.
   На эту высоту поднимается только КАРТИНКА (render.js): модель света и роста
   считает куст от пола, как раньше, — иначе поедет баланс систем.        */
const POT_H = { soil:0.17, coco:0.12, dwc:0.21, nft:0.18, aero:0.19 };
function vesselStandY(w){
  return ((w && w.profile) === 'room' || (w && w.profile) === 'balcony') ? 0 : 0.16;
}
function plantBaseY(w){
  const sys = (w && w.sys) || 'soil';
  return vesselStandY(w) + (POT_H[sys] || POT_H.soil);
}
function nodeY(C, i, base){ return (base||0) + 0.06 + i*C.internode*0.8; }

function leafGeom(lf, C, px, py, pz){
  const tilt = lf.tilt, az = lf.az;
  const dir = {x: Math.sin(tilt)*Math.cos(az), y: Math.cos(tilt), z: Math.sin(tilt)*Math.sin(az)};
  let sx = -dir.z, sy = 0, sz = dir.x;
  const sl = Math.hypot(sx,sz)||1; sx/=sl; sz/=sl;
  let nrm = {x: dir.y*sz - dir.z*sy, y: dir.z*sx - dir.x*sz, z: dir.x*sy - dir.y*sx};
  if (nrm.y < 0) nrm = {x:-nrm.x, y:-nrm.y, z:-nrm.z};
  const petiole = lf.petiole || 0.085;
  const base = {x: px + Math.cos(az)*petiole, y: py, z: pz + Math.sin(az)*petiole};
  const len = Math.min(0.42, Math.sqrt(Math.max(1e-4,lf.area)*2.05));
  const wid = lf.area/Math.max(0.02, len);
  const mid = {x: base.x+dir.x*len*0.45, y: base.y+dir.y*len*0.45, z: base.z+dir.z*len*0.45};
  const tip = {x: base.x+dir.x*len, y: base.y+dir.y*len, z: base.z+dir.z*len};
  const S = {x:sx, y:sy, z:sz};
  const corners = [
    base,
    {x: mid.x+S.x*wid*0.5, y: mid.y+S.y*wid*0.5, z: mid.z+S.z*wid*0.5},
    tip,
    {x: mid.x-S.x*wid*0.5, y: mid.y-S.y*wid*0.5, z: mid.z-S.z*wid*0.5}
  ];
  const cen = corners.reduce((a,c)=>({x:a.x+c.x/4, y:a.y+c.y/4, z:a.z+c.z/4}), {x:0,y:0,z:0});
  return {corners, dir, side:S, normal:nrm, base, tip, cen, len, wid};
}

/* ---------------- Свет: воксельная LAD + трассировка ---------------- */
const CELL = 0.25;
const NX = Math.round(CFG.floorW/CELL), NY = 14, NZ = Math.round(CFG.floorD/CELL);
const CELLV = CELL*CELL*CELL;

function totalLAI(w){
  const C = CROPS[w.crop];
  let a = 0;
  for (const p of w.plants) for (const lf of p.leaves) if (!lf.dead) a += lf.area;
  return a/(CFG.floorW*CFG.floorD);
}

function computeLight(w, dtH){
  const C = CROPS[w.crop];
  const out = outsideClimate(w, w.doy, w.hour + (dtH||0)*0.5);
  w.out = out;
  const sun = sunVector(out.el, out.azScene===undefined?out.az:out.azScene);
  // лампа слушается игрока; отказ оборудования и отсутствие питания гасят её
  const wantLamp = !!w.ctrl.lampOn && !!w.power;
  const lampOn = wantLamp && ((w.has.led && w.equip.lamp.ok) || w.has.lampBase);
  const stripOn = wantLamp && w.has.ledStrip;
  const tauGH = CFG.glassTau*(PROFILES[w.profile].tauF||1)*(1-CFG.frameShade);
  const shadeF = (w.has.shade && w.ctrl.shadeOn) ? 0.65 : 1;
  const directIn = out.ppfd*tauGH*shadeF;
  const diffuseIn = out.ppfd*tauGH*0.28*shadeF;

  const lad = new Float32Array(NX*NY*NZ);
  const leaves = [];
  for (const p of w.plants) for (const lf of p.leaves){
    if (lf.dead || lf.area < 1e-4) continue;
    const g = leafGeom(lf, C, p.x, nodeY(C, lf.i), p.z);
    leaves.push({lf, p, g});
    let mnx=1e9,mxx=-1e9,mny=1e9,mxy=-1e9,mnz=1e9,mxz=-1e9;
    for (const c of g.corners){
      mnx=Math.min(mnx,c.x); mxx=Math.max(mxx,c.x);
      mny=Math.min(mny,c.y); mxy=Math.max(mxy,c.y);
      mnz=Math.min(mnz,c.z); mxz=Math.max(mxz,c.z);
    }
    const ix0=clamp(Math.floor(mnx/CELL),0,NX-1), ix1=clamp(Math.floor(mxx/CELL),0,NX-1);
    const iy0=clamp(Math.floor(mny/CELL),0,NY-1), iy1=clamp(Math.floor(mxy/CELL),0,NY-1);
    const iz0=clamp(Math.floor(mnz/CELL),0,NZ-1), iz1=clamp(Math.floor(mxz/CELL),0,NZ-1);
    const nc = (ix1-ix0+1)*(iy1-iy0+1)*(iz1-iz0+1);
    for (let iy=iy0;iy<=iy1;iy++) for (let iz=iz0;iz<=iz1;iz++) for (let ix=ix0;ix<=ix1;ix++)
      lad[(iy*NZ+iz)*NX+ix] += lf.area/nc/CELLV;
  }
  const sample = (x,y,z) => {
    const ix = Math.floor(x/CELL), iy = Math.floor(y/CELL), iz = Math.floor(z/CELL);
    if (ix<0||ix>=NX||iy<0||iy>=NY||iz<0||iz>=NZ) return 0;
    return lad[(iy*NZ+iz)*NX+ix];
  };

  const K = 5, k = 0.55, step = 0.16, jitter = 0.035;
  let sum = 0, sumLamp = 0, cnt = 0, laiAboveAll = 0;
  const lampPPFD = w.has.led ? (w.upg.ledBoost?280:190) : (w.has.lampBase?90:0);

  for (const L of leaves){
    const c = L.g.cen;
    let laiAbove = 0;
    for (let y = c.y+0.02; y < CFG.ridgeY; y += CELL) laiAbove += sample(c.x, y, c.z)*CELL;
    laiAboveAll += laiAbove;

    const n = L.g.normal;
    const cosSun = Math.max(0, n.x*sun.x + n.y*sun.y + n.z*sun.z);
    let Tsum = 0;
    for (let r=0;r<K;r++){
      let dx = sun.x + (rnd(w)-0.5)*jitter, dy = sun.y + (rnd(w)-0.5)*jitter, dz = sun.z + (rnd(w)-0.5)*jitter;
      const l = Math.hypot(dx,dy,dz)||1; dx/=l; dy/=l; dz/=l;
      let tau = 1, x = c.x + dx*0.05, y = c.y + dy*0.05, z = c.z + dz*0.05;
      for (let s=0;s<26 && y < CFG.ridgeY;s++){
        tau *= Math.exp(-k*sample(x,y,z)*step);
        x += dx*step; y += dy*step; z += dz*step;
        if (x<0||x>CFG.floorW||z<0||z>CFG.floorD) break;
      }
      Tsum += tau;
    }
    const T = Tsum/K;
    const dirAbs = directIn*T*Math.max(cosSun, 0.03);
    const difAbs = diffuseIn*Math.exp(-0.6*laiAbove)*0.45;
    const lampAbs = (lampOn ? lampPPFD*Math.exp(-0.6*laiAbove)*0.55 : 0)
                  + (stripOn ? (w.has.strip2?90:60)*Math.exp(-0.8*laiAbove)*0.5 : 0);
    const I = 0.86*(dirAbs + difAbs + lampAbs);
    sumLamp += 0.86*lampAbs;
    L.lf.Iabs = I;
    L.lf.relLight = clamp(I/420, 0.05, 1.2);
    sum += I; cnt++;
  }

  const meanLeaf = cnt? sum/cnt : 0;
  const meanLamp = cnt? sumLamp/cnt : 0;
  // DLI считаем по свету над кроной — так его измеряют в теплице.
  const lampCanopy = (lampOn ? lampPPFD*0.85 : 0) + (stripOn ? (w.has.strip2?90:60)*0.85 : 0);
  const canopyPPFD = out.ppfd*tauGH*shadeF + lampCanopy;
  w.light = {
    outside: out.ppfd, directIn, diffuseIn, sun,
    meanLeaf, meanLamp,
    canopyLAI: totalLAI(w),
    lampOn, stripOn, cloud: out.cloud
  };
  w.dliAcc = (w.dliAcc||0) + canopyPPFD*3600/1e6*(dtH||0);
  if (canopyPPFD > 20) w.photoHoursDay = (w.photoHoursDay||0) + (dtH||0);
  w.dliLampAcc = (w.dliLampAcc||0) + lampCanopy*3600/1e6*(dtH||0);
  if (lampOn || stripOn) w.lampHoursDay = (w.lampHoursDay||0) + (dtH||0);
  return w.light;
}

/* ---------------- Свет за сутки (DLI) и фотопериод ----------------
   DLI — сколько молей фотонов упало на квадратный метр за сутки. Это тот же
   свет, что модель уже считает по листьям, только собранный в понятное число:
   «12 моль из 20» игроку говорит больше, чем «PAR 180».                     */
const _dayLenCache = {};
function dayLength(w, doy){
  const lat = ((w && w.site && w.site.lat) || CFG.lat);
  const d = clamp(Math.round(doy==null ? ((w && w.doy) || 172) : doy), 1, 365);
  const key = lat.toFixed(1)+'|'+d;
  if (_dayLenCache[key] !== undefined) return _dayLenCache[key];
  let n = 0;
  for (let h=0; h<24; h+=0.25) if (sunPosition(d, h+0.125, lat).el > 0) n += 0.25;
  _dayLenCache[key] = n;
  return n;
}
function dliInfo(w){
  const C = CROPS[w.crop];
  const val = w.dliAcc || 0;
  const yest = w.dliYest || 0;
  const min = C.dliMin, tgt = C.dliTgt, max = C.dliMax;
  // вердикт — по целым суткам: сегодняшний день ещё копится, судить по нему рано
  const ref = (w.hour >= 21 || yest < 0.5) ? val : yest;
  const pct = clamp(val/Math.max(0.01,tgt), 0, 1.4);
  const verdict = ref > max ? 'больше нормы'
                : ref >= min ? 'в норме'
                : ref >= min*0.75 ? 'чуть меньше нормы'
                : ref >= min*0.5 ? 'меньше нормы' : 'критически мало света';
  const need = Math.max(0, tgt - ref);
  const lampPPFD = w.has.led ? (w.upg.ledBoost?280:190) : (w.has.lampBase?90:0);
  const stripPPFD = w.has.ledStrip ? (w.has.strip2?90:60) : 0;
  // один час досветки даёт PPFD×3600/1e6 молей, но до листа доходит ~половина
  const perHour = Math.max(0.02, (lampPPFD+stripPPFD)*0.85*3600/1e6);
  const photo = (w.hour >= 21 || !(w.photoHoursYest > 0)) ? (w.photoHoursDay||0) : w.photoHoursYest;
  const photoVerdict = photo > C.photoMax + 0.5 ? 'длинный день'
                     : photo < C.photoMin - 0.5 ? 'короткий день' : 'в норме';
  return {val, yest, ref, min, tgt, max, pct, verdict, need, perHour,
          hours: need>0 ? need/perHour : 0,
          gain14: perHour*14, reachable: need <= perHour*14,
          day: dayLength(w, w.doy), lampHours: w.lampHoursDay || 0,
          photo, photoVerdict, photoMin: C.photoMin, photoMax: C.photoMax,
          lampDLI: w.dliLampAcc || 0};
}

