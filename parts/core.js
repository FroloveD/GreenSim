function buyItem(w, id){
  const shop = SHOP();
  for (const g of shop) for (const it of g.items){
    if (it.id !== id) continue;
    if (it.req && !it.req(w)) return {ok:false, msg:'Недоступно'};
    if (id === 'repair'){
      // чиним по одному, начиная с самого важного: денег на всё может не хватить,
      // и тогда игрок чинит то, что сильнее всего влияет на урожай, а не ждёт месяцами
      const order = ['heater','fan','lamp','dosing','co2','sensor'];
      const broken = order.filter(k=>w.equip[k] && !w.equip[k].ok);
      if (!broken.length) return {ok:false, msg:'Всё работает'};
      const priceOf = k => Math.round((w.has.insurance ? EQUIP_DEFS[k].repair*0.4 : EQUIP_DEFS[k].repair)*shopPriceFactor(w));
      let total = 0, fixed = [];
      for (const k of broken){
        const p = priceOf(k);
        if (w.money - total < p) continue;          // на это не хватает — чиним, что можем
        total += p;
        const eq = w.equip[k]; eq.ok = true; eq.stuck = false; eq.down = 0;
        fixed.push(EQUIP_DEFS[k].name);
      }
      if (!fixed.length){
        const min = Math.min(...broken.map(priceOf));
        return {ok:false, msg:`Недостаточно средств: самый дешёвый ремонт ${money(min)}`};
      }
      w.money -= total; w.cost.repair += total;
      const rest = broken.length - fixed.length;
      w.log.unshift({t:'Д'+w.day, m:`Ремонт: ${fixed.join(', ')} — ${money(total)}` + (rest?` (осталось сломано: ${rest})`:''), k:'hl'});
      return {ok:true, msg:`Ремонт: ${fixed.join(', ')} — ${money(total)}` + (rest?`. Не хватило на остальное: ${rest}`:'')};
    }
    if (it.id === 'whSection'){
      const r = addSection(w);
      return r.ok ? {ok:true, msg:`Склад: ${w.wh.sections} секций (−${money(r.cost)})`} : {ok:false, msg:r.msg};
    }
    const cost = shopItemCost(w, it);
    if (w.money < cost) return {ok:false, msg:'Недостаточно средств'};
    // место на складе: расходники не бесконечны
    if (it.bulk){
      const free = whFreeL(w);
      if (free < it.bulk)
        return {ok:false, msg:`Склад переполнен: нужно ${it.bulk} л, свободно ${Math.round(free)} л`};
    }
    w.money -= cost;
    const before = w.revenue;
    it.buy && it.buy(w);
    // если покупка — это оборудование из списка отказов, запоминаем дату и цену:
    // по ним считается гарантия (180–364 дня с покупки)
    const EQUIP_OF_ITEM = {
      led:['lamp'], ledStrip:['lamp'], ledBoost:['lamp'], film:['heater'], screen:['heater'],
      climatePC:['heater','fan'], secondSensor:['sensor'], dosing:['dosing'],
      co2_50:['co2'], co2_200:['co2'], reliability:['heater','fan','lamp','co2','dosing','sensor']
    };
    for (const k of (EQUIP_OF_ITEM[id] || [])){
      const eq = w.equip[k];
      if (!eq) continue;
      eq.since = w.day; eq.paid = EQUIP_DEFS[k] ? EQUIP_DEFS[k].price : cost;
      eq.claimed = false;
    }
    if (!it.dynamic) w.cost.upgrade += cost;
    else if (it.bucket) w.cost[it.bucket] += cost;
    w.log.unshift({t:'Д'+w.day, m:`Покупка: ${it.name} (−${money(cost)})`, k:''});
    return {ok:true, msg:it.name+' куплено'};
  }
  return {ok:false, msg:'Не найдено'};
}

/* ---------------- Клонирование и прогноз ---------------- */
function cloneWorld(w){
  const seen = new Map();
  const cl = (v) => {
    if (v === null || typeof v !== 'object') return v;
    if (seen.has(v)) return seen.get(v);
    if (Array.isArray(v)){
      const a = []; seen.set(v,a);
      for (let i=0;i<v.length;i++) a.push(cl(v[i]));
      return a;
    }
    const o = {}; seen.set(v,o);
    for (const k in v) o[k] = cl(v[k]);
    return o;
  };
  return cl(w);
}

/** Запуск прогноза: клон мира + сдвиг PRNG (прогноз не знает будущего шума) */
/* ---------------- Сохранение: сериализация и восстановление графа ----------------
   Узлы графа (node/parent/children) — только «скелет» для правил; в логике роста и рендере
   они не читаются, поэтому в сейв не попадают, а на загрузке пересобираются из массивов. */
const SAVE_VERSION = 2;

function serializeWorld(w){
  return JSON.stringify({ v:SAVE_VERSION, ts:Date.now(), world:w },
    (k, val) => (k==='node'||k==='root'||k==='parent'||k==='children') ? undefined : val);
}

function rebuildGraph(w){
  if (!w || !w.plants) return w;
  for (const p of w.plants){
    p.root = {id:(_oid++), type:'plant', parent:null, children:[], label:'plant#'+p.id};
    const stems = {};
    for (let i=0;i<(p.nPhy||0);i++) stems[i] = organNode(p.root, 'stem', 'internode#'+(i+1));
    for (const lf of p.leaves) lf.node = organNode(stems[lf.i] || p.root, 'leaf', 'leaf#'+(lf.i+1));
    for (const tr of p.trusses){
      tr.node = organNode(stems[tr.i] || p.root, 'truss', 'truss#'+tr.i);
      for (const f of tr.fruits) f.node = organNode(tr.node, 'fruit', 'fruit');
    }
    if (!p.organs) p.organs = [];
  }
  return w;
}

