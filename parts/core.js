const WARRANTY = { fromDay:180, toDay:364, payDays:7 };

/* Есть ли это оборудование в мире: клапан CO₂ не может сломаться там, где его нет. */
/* есть ли вообще чем светить: лампа-лента (в стартовом наборе), LED-лента, ЛЕД */
function hasLight(w){
  return !!(w && w.has && (w.has.led || w.has.ledStrip || w.has.lampBase));
}
/* горит ли свет прямо сейчас. Лампа и лента — два разных флага (лента дешевле
   и слабее), а игроку важно одно: свет есть или нет. Раньше сцена смотрела
   только на light.lampOn и при одной ленте оставалась тёмной. */
function lightLit(w){
  return !!(w && w.light && (w.light.lampOn || w.light.stripOn));
}
function lightName(w){
  if (!w) return 'нет';
  if (w.has.led) return 'LED-досветка';
  if (w.has.ledStrip) return 'LED-лента';
  if (w.has.lampBase) return 'лампа-лента';
  return 'нет';
}
/* Включить/выключить досветку. Одна функция на все входы: кнопка «Досветка»
   в панели под сценой, клик по светильнику в сцене и переключатель в
   «Параметрах». Раньше каждый вход проверял своё (кнопка требовала именно
   LED за 2800 € и при дешёвой ленте отвечала «купите LED»). */
function toggleLamp(w){
  if (!w || !w.has || !hasLight(w))
    return {ok:false, on:false, name:'нет', msg:'Лампы нет — купите в магазине'};
  w.ctrl.lampEnabled = !w.ctrl.lampEnabled;
  const on = !!w.ctrl.lampEnabled;
  w.ctrl.lampOn = on && !!w.power && hasLight(w);
  const name = lightName(w);
  let msg = on ? name+': включена' : 'Досветка выключена — за свет не платите';
  if (on && !w.power) msg = name+': включена, но нет электричества';
  // рука игрока сильнее расписания: нажал кнопку — таймер света выключается,
  // иначе автоматика вернула бы своё состояние на следующем шаге и кнопка «не работала»
  let timerOff = false;
  if (w.auto && w.auto.lamp && w.auto.lamp.on){ setAuto(w, 'lamp', false); timerOff = true; msg += '. Таймер света выключен'; }
  return {ok:true, on, name, msg, timerOff};
}

/* сколько дней проживут баки при вчерашнем расходе (null — данных ещё нет) */
function tankDays(w, what){
  const last = (w.history && w.history.length) ? w.history[w.history.length-1] : null;
  if (!last) return null;
  if (what==='water'){ const r = last.waterM3||0; return r>0.001 ? w.stock.waterM3/r : null; }
  if (what==='fert'){  const r = last.fertKg||0;  return r>0.001 ? w.stock.fertKg/r : null; }
  if (what==='co2'){   const r = last.co2Kg||0;   return r>0.001 ? w.stock.co2Kg/r : null; }
  return null;
}
function fmtHour(h){ h=Math.round(h); return (h>=24?'24:00':String(((h%24)+24)%24).padStart(2,'0')+':00'); }
/* что сейчас говорит будильник досветки — одной строкой для подсказки */
function alarmState(w){
  if (!w || !w.ctrl || !w.ctrl.alarmOn || !hasLight(w)) return 'Будильник выключен.';
  const from = w.ctrl.alarmFrom, to = w.ctrl.alarmTo, h = w.hour;
  const inside = from < to ? (h >= from && h < to) : (h >= from || h < to);
  if (inside) return w.ctrl.lampEnabled ? 'Окно досветки: лампа включена ✓' : 'Окно досветки: пора включить лампу';
  return w.ctrl.lampEnabled ? 'Вне окна: лампу пора выключить' : 'Вне окна досветки: всё выключено ✓';
}
function equipInstalled(w, k){
  if (k === 'co2') return !!w.has.co2;
  if (k === 'dosing') return !!w.has.dosing;
  return true;
}
function riskTick(w, dtH){
  const dtD = dtH/24;
  // износ и отказы
  for (const k in w.equip){
    const eq = w.equip[k], def = EQUIP_DEFS[k];
    if (!eq || !def) continue;
    if (!equipInstalled(w, k)) continue;
    if (!eq.ok){ eq.down += dtH; continue; }
    const p = def.failP*dtD*(w.diffFail||1)*(w.has.service?0.35:1)*(w.upg.reliability?0.6:1);
    if (rnd(w) < p){
      eq.ok = false; eq.down = 0; eq.stuck = (k==='co2') && rnd(w)<0.5;
      w.events.push({kind:'breakdown', equip:k, days:0});
      w.incidents = (w.incidents||0)+1;
      // гарантия: возраст прибора от установки (для стартового — от 1-го дня сезона)
      const age = w.day - (eq.since || 1);
      const claim = age >= WARRANTY.fromDay && age <= WARRANTY.toDay && !eq.claimed;
      if (claim){
        eq.claimed = true;
        const eur = Math.round(eq.paid || def.price);
        w.warranty = w.warranty || [];
        w.warranty.push({k, name:def.name, eur, due:w.day + WARRANTY.payDays, day:w.day, age});
        w.log.unshift({t:'Д'+w.day, m:`Гарантия: ${def.name} (${age} дн с установки) — возврат ${money(eur)} через ${WARRANTY.payDays} дн`, k:'hl'});
        w.alarmPing = {text:`Гарантийный случай: ${def.name} · ${money(eur)} придут ${fmtDate(w.doy + WARRANTY.payDays)}`};
      } else {
        w.log.unshift({t:'Д'+w.day, m:`Отказ: ${def.name}. Ремонт ${money(def.repair)} (Магазин → Сервис)`, k:'bad'});
      }
    }
  }
  // гарантийные возвраты: деньги приходят ровно через 7 дней, а не сразу
  if (w.warranty && w.warranty.length){
    for (let i=w.warranty.length-1; i>=0; i--){
      const r = w.warranty[i];
      if (w.day >= r.due){
        w.money += r.eur;
        w.revenue += r.eur;              // это возврат, а не выручка, но баланс должен сойтись
        w.log.unshift({t:'Д'+w.day, m:`Гарантийный возврат: ${r.name} — +${money(r.eur)}`, k:'hl'});
        w.alarmPing = {text:`Гарантия: ${r.name} — вернули ${money(r.eur)}`};
        w.warranty.splice(i,1);
      }
    }
  }
  // датчики «плывут»
  const dF = (w.diffDrift||1);
  w.drift.temp += (rnd(w)-0.45)*0.05*dtD*dF;
  w.drift.rh   += (rnd(w)-0.5)*0.12*dtD*dF;
  w.drift.co2  += (rnd(w)-0.5)*1.2*dtD*dF;
  w.drift.soil = (w.drift.soil||0) + (rnd(w)-0.45)*0.5*dtD*dF;   // щуп в земле «плывёт» тоже
  const nz = () => (rnd(w)-0.5)*0.3;
  w.meas.temp = w.temp + w.drift.temp + nz();
  w.meas.rh   = clamp(w.rh + w.drift.rh + nz()*2, 20, 100);
  w.meas.co2  = Math.max(330, w.co2 + w.drift.co2 + nz()*4);
  w.meas.moist = clamp((w.moist===undefined?SOIL.m0:w.moist) + w.drift.soil + nz()*1.5, 0, 100);

  // погода: планируем события заранее (чтобы прогноз мог их показать)
  for (let i=w.events.length-1;i>=0;i--){
    const ev = w.events[i];
    if (ev.kind==='breakdown'){ w.events.splice(i,1); continue; }
    if (ev.inFuture){ ev.inDays -= dtD; if (ev.inDays<=0){ ev.inFuture=false; ev.days = ev.len; } continue; }
    ev.days -= dtD;
    if (ev.days<=0) w.events.splice(i,1);
  }
  // раз в день — шанс новых погодных событий
  if (!w._planTomorrow){
    w._planTomorrow = true;
    const r = rnd(w)/(w.diffEvent||1);
    if (r < 0.05) w.events.push({kind:'cold', inFuture:true, inDays:4+Math.floor(rnd(w)*7), len:2+Math.floor(rnd(w)*2), severity:6+rnd(w)*5, label:'Похолодание'});
    else if (r < 0.10) w.events.push({kind:'heat', inFuture:true, inDays:4+Math.floor(rnd(w)*7), len:2+Math.floor(rnd(w)*3), severity:4+rnd(w)*4, label:'Жара'});
    else if (r < 0.16) w.events.push({kind:'overcast', inFuture:true, inDays:3+Math.floor(rnd(w)*6), len:4+Math.floor(rnd(w)*6), severity:0, label:'Затяжная облачность'});
    else if (r < 0.18) w.events.push({kind:'blackout', inFuture:true, inDays:3+Math.floor(rnd(w)*8), len:0.4+rnd(w)*0.3, severity:0, label:'Отключение электричества'});
  }
  // электричество
  w.power = true;
  for (const ev of w.events) if (ev.kind==='blackout' && !ev.inFuture) w.power = false;

  // вредители
  if (!w.pest.active && w.day>12 && rnd(w) < 0.004*dtH*(PROFILES[w.profile].riskF||1)*(w.has.biocontrol?0.4:1)*(w.has.sticky?0.75:1)){
    w.pest.active = true; w.pest.level = 0.12;
    w.log.unshift({t:'Д'+w.day, m:'Обнаружен паутинный клещ. Нужна обработка (Магазин → Защита)', k:'bad'});
  }
  if (w.pest.active) w.pest.level = clamp(w.pest.level + (w.temp>27?0.010:0.004)*dtH, 0, 1);
}


/* ---------------- Склад: ёмкость, партии, порча ---------------- */
function whCap(w){ return (w.wh.sections||2)*WH.sectionL; }
function whSupplyL(w){
  const s = w.stock;
  return s.fertKg*WH.bulk.fertKg + s.co2Kg*WH.bulk.co2Kg + s.seeds*WH.bulk.seed;
}
function whHarvestL(w){
  let L = 0;
  for (const l of w.wh.lots) L += l.kg*WH.bulkHarvest;
  return L;
}
function whUsedL(w){ return whSupplyL(w) + whHarvestL(w); }
function whFreeL(w){ return Math.max(0, whCap(w) - whUsedL(w)); }
function storeKg(w, crop){
  let kg = 0;
  for (const l of w.wh.lots) if (!crop || l.crop===crop) kg += l.kg;
  return kg;
}
/* сколько литров займёт покупка расходников */
function needL(item, w){
  const base = item.bulk || 0;
  return base;
}
/* партия урожая: складываем в одну на день, качество — среднее */
function addLot(w, crop, kg, quality){
  if (kg <= 0) return;
  const shelf = CROPS[crop].shelfDays;
  const freeKg = whFreeL(w)/WH.bulkHarvest;
  const put = Math.min(kg, freeKg);
  const lost = kg - put;
  if (put > 0.001){
    let lot = w.wh.lots.find(l=>l.crop===crop && l.day===w.day);
    if (!lot){ lot = {crop, day:w.day, age:0, shelf, kg:0, q:quality}; w.wh.lots.push(lot); }
    lot.q = (lot.q*lot.kg + quality*put)/(lot.kg+put);
    lot.kg += put;
  }
  if (lost > 0.001){
    w.wh.wasteKg += lost; w.wh.wasteEur += lost*CROPS[crop].price*w.profilePriceF;
    w.log.unshift({t:'Д'+w.day, m:`Склад полон: ${Math.round(lost)} кг осталось на грядке`, k:'bad'});
  }
  return {put, lost};
}

/* ---------------- Рынок цен ----------------
   Цена = базовая × профиль × сезон × недельный шум.
   Сезон — это настоящая аграрная кривая: тепличный томат дорог зимой и в начале
   весны (своего урожая нет, везут издалека) и дешевеет к августу, когда рынок
   завален. Индексы округлённые, по обычной для России динамике оптовых цен.   */
const PRICE_SEASON = {
  tomato:  [1.32, 1.38, 1.30, 1.12, 0.97, 0.86, 0.74, 0.71, 0.79, 0.94, 1.12, 1.26],
  cherry:  [1.26, 1.30, 1.24, 1.10, 0.98, 0.90, 0.82, 0.80, 0.86, 0.97, 1.10, 1.22],
  cucumber: [1.40, 1.46, 1.34, 1.06, 0.86, 0.76, 0.66, 0.65, 0.76, 0.93, 1.16, 1.34],
  lettuce: [1.18, 1.20, 1.14, 1.06, 0.98, 0.93, 0.91, 0.93, 0.99, 1.05, 1.11, 1.16]
};
/* сезонный множитель на конкретный день года */
function seasonFactor(crop, doy){
  const S = PRICE_SEASON[crop] || PRICE_SEASON.tomato;
  return normAt(S, doy);
}
/* что будет с ценой через N дней — для подсказки «продать или подождать» */
function seasonAhead(w, crop, days){
  const now = seasonFactor(crop, w.doy);
  const next = seasonFactor(crop, w.doy + (days||7));
  return {now, next, pct: now ? (next/now - 1) : 0};
}

/* ---------------- Рынок цен ---------------- */
function priceToday(w, crop){
  const C = CROPS[crop||w.crop];
  const m = (w.market && w.market.mult && w.market.mult[C.id]) || 1;
  return C.price * w.profilePriceF * seasonFactor(C.id, w.doy) * m * (w.repF || 1);
}
function marketTrend(w, crop){
  const h = (w.market.hist[crop]||[]);
  return h.length>1 ? h[h.length-1]-h[h.length-2] : 0;
}
function marketTick(w){
  if (!w.market) return;
  for (const id in CROPS){
    const m = w.market.mult[id] || 1;
    // шум ходит вокруг СЕЗОННОЙ нормы: ±15% за неделю плюс редкий «выстрел»
    let next = m + (rnd(w)-0.5)*0.06;
    if (rnd(w) < 0.06) next += (rnd(w)-0.45)*0.22;
    next = clamp(next, 0.82, 1.18);
    w.market.mult[id] = next;
    // в историю пишем итоговую цену (сезон × шум) — по ней рисуется график
    const eff = seasonFactor(id, w.doy) * next;
    const h = w.market.hist[id] = w.market.hist[id] || [];
    h.push(+eff.toFixed(3)); if (h.length > 30) h.shift();
  }
}

/* ---------------- Порча урожая ---------------- */
function whRot(w){
  let lost = 0, eur = 0;
  const keep = [];
  for (const lot of w.wh.lots){
    lot.age++;
    const shelf = lot.shelf || CROPS[lot.crop].shelfDays;
    const dead = lot.age > shelf*2;
    const before = lot.kg;
    lot.kg = dead ? 0 : lot.kg*(1 - 1/shelf);
    lost += before - lot.kg;
    eur += (before - lot.kg)*CROPS[lot.crop].price*w.profilePriceF*lot.q;
    if (lot.kg > 0.4) keep.push(lot);
    else if (lot.kg > 0) { lost += lot.kg; eur += lot.kg*CROPS[lot.crop].price*w.profilePriceF*lot.q; }
  }
  w.wh.lots = keep;
  if (lost > 0.5){
    w.wh.wasteKg += lost; w.wh.wasteEur += eur;
    w.log.unshift({t:'Д'+w.day, m:`Порча на складе: −${Math.round(lost)} кг (${money(Math.round(eur))})`, k:'warn'});
  }
  return {lost, eur};
}

/* ---------------- Продажа со склада ---------------- */
/* ---------------- Себестоимость килограмма ----------------
   Сколько стоило вырастить то, что уже собрано: все расходы сезона на кг.
   Сравниваем с ценой дня — это и есть ответ «я зарабатываю или доедаю склад». */
function seasonCost(w){ return Object.values(w.cost||{}).reduce((s,x)=>s+(x||0),0); }
function costPerKg(w){
  const kg = w.harvestedKg || 0;
  if (kg < 0.05) return null;
  return seasonCost(w)/kg;
}
function marginInfo(w, crop){
  const c = costPerKg(w);
  const price = priceToday(w, crop || w.crop);
  if (c === null) return {cost:null, price, margin:null, pct:null};
  return {cost:c, price, margin:price-c, pct:(price-c)/Math.max(0.01,price)};
}
/* оценка себестоимости «наперёд»: вчерашние расходы на вчерашний урожай */
function costPerKgDay(w){
  const h = (w.history && w.history.length) ? w.history[w.history.length-1] : null;
  if (!h || !(h.harvestedKg>0.05)) return null;
  return (h.cost||0)/(h.harvestedKg||1);
}

function lotQuality(lot){ return clamp(lot.q*(1 - 0.55*lot.age/Math.max(1,lot.shelf*1.4)), 0.35, 1); }
function sellHarvest(w, crop, kgWant){
  crop = crop || w.crop;
  const lots = w.wh.lots.filter(l=>l.crop===crop).sort((a,b)=>b.age-a.age);   // старые первыми
  let left = kgWant==null ? Infinity : kgWant;
  let kg = 0, eur = 0;
  for (const lot of lots){
    if (left <= 0.01) break;
    const take = Math.min(lot.kg, left);
    const kq = lotQuality(lot);
    kg += take; eur += take*priceToday(w, crop)*kq;
    lot.kg -= take; left -= take;
  }
  w.wh.lots = w.wh.lots.filter(l=>l.kg > 0.05);
  if (kg <= 0.05) return {kg:0, eur:0, ok:false};
  w.money += eur; w.revenue += eur; w.soldKg = (w.soldKg||0) + kg; w.soldEur = (w.soldEur||0) + eur;
  w.cost.labor += CFG.laborHour*0.03; w.money -= CFG.laborHour*0.03;
  w.log.unshift({t:'Д'+w.day, m:`Продано ${Math.round(kg)} кг по ${money2((priceToday(w,crop)).toFixed(2))}/кг: +${money(Math.round(eur))}`, k:'hl'});
  return {kg, eur, ok:true};
}

